def read_csv_safe(path):
    try:
        return pd.read_csv(path) if path.exists() else None
    except Exception as error:
        print(f"Could not read {path.name}: {error}")
        return None


def load_test_confidence_table():
    table = read_csv_safe(MOBILENET_REPORT_DIR / "test_error_analysis.csv")
    if table is None or not {"confidence", "correct"} <= set(table.columns):
        return None
    table = table.copy()
    table["correct"] = table["correct"].astype(str).str.lower() == "true"
    return table[["confidence", "correct"]].dropna()


TEST_CONFIDENCE = load_test_confidence_table()


def calibration_text(tier):
    """How often were test predictions in this confidence tier correct?"""
    if TEST_CONFIDENCE is None or len(TEST_CONFIDENCE) == 0:
        return ""
    conf = TEST_CONFIDENCE["confidence"]
    if tier == "high":
        subset = TEST_CONFIDENCE[conf >= HIGH_CONFIDENCE]
        label = f"confidence >= {HIGH_CONFIDENCE:.0%}"
    elif tier == "moderate":
        subset = TEST_CONFIDENCE[
            (conf >= MODERATE_CONFIDENCE) & (conf < HIGH_CONFIDENCE)
        ]
        label = f"confidence {MODERATE_CONFIDENCE:.0%}-{HIGH_CONFIDENCE:.0%}"
    else:
        subset = TEST_CONFIDENCE[conf < MODERATE_CONFIDENCE]
        label = f"confidence < {MODERATE_CONFIDENCE:.0%}"
    if len(subset) == 0:
        return ""
    accuracy = subset["correct"].mean()
    return (
        f"On the held-out test set, {accuracy:.0%} of predictions with "
        f"{label} were correct (n = {len(subset)})."
    )



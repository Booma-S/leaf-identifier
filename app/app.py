def quality_report(rgb, coverage):
    gray = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY)
    scale = 512 / max(gray.shape)
    if scale < 1:
        gray = cv2.resize(gray, None, fx=scale, fy=scale,
                          interpolation=cv2.INTER_AREA)

    sharpness = float(cv2.Laplacian(gray, cv2.CV_64F).var())
    brightness = float(gray.mean())
    contrast = float(gray.std())

    def chip(title, value, status, note):
        return (
            f'<div class="qc {status}"><div class="qc-t">{esc(title)}</div>'
            f'<div class="qc-v">{esc(value)}</div>'
            f'<div class="qc-n">{esc(note)}</div></div>'
        )

    if sharpness < 60:
        sharp_chip = chip("Sharpness", f"{sharpness:.0f}", "bad",
                          "Blurry - retake in focus")
    elif sharpness < 150:
        sharp_chip = chip("Sharpness", f"{sharpness:.0f}", "warn",
                          "Acceptable")
    else:
        sharp_chip = chip("Sharpness", f"{sharpness:.0f}", "good", "Sharp")

    if brightness < 70:
        light_chip = chip("Exposure", f"{brightness:.0f}/255", "warn",
                          "Dark image")
    elif brightness > 215:
        light_chip = chip("Exposure", f"{brightness:.0f}/255", "warn",
                          "Over-exposed")
    else:
        light_chip = chip("Exposure", f"{brightness:.0f}/255", "good",
                          "Well exposed")

    if contrast < 30:
        contrast_chip = chip("Contrast", f"{contrast:.0f}", "warn",
                             "Low contrast")
    else:
        contrast_chip = chip("Contrast", f"{contrast:.0f}", "good",
                             "Good contrast")

    if coverage < 0.03:
        cover_chip = chip("Leaf coverage", f"{coverage:.0%}", "bad",
                          "Leaf too small in frame")
    elif coverage > 0.90:
        cover_chip = chip("Leaf coverage", f"{coverage:.0%}", "warn",
                          "Background not visible")
    else:
        cover_chip = chip("Leaf coverage", f"{coverage:.0%}", "good",
                          "Leaf clearly isolated")

    return (
        '<div class="qc-wrap"><div class="sec-title">Input image quality '
        '<span class="muted">(heuristic checks)</span></div>'
        f'<div class="qc-grid">{sharp_chip}{light_chip}{contrast_chip}'
        f"{cover_chip}</div></div>"
    )



def fill_holes(mask):
    mask = (mask > 0).astype(np.uint8) * 255
    flood = mask.copy()
    h, w = mask.shape
    flood_mask = np.zeros((h + 2, w + 2), np.uint8)
    cv2.floodFill(flood, flood_mask, (0, 0), 255)
    holes = cv2.bitwise_not(flood)
    return cv2.bitwise_or(mask, holes)


def largest_component(mask):
    count, labels, stats, _ = cv2.connectedComponentsWithStats(
        (mask > 0).astype(np.uint8), connectivity=8
    )
    if count <= 1:
        return np.zeros_like(mask)
    label = 1 + np.argmax(stats[1:, cv2.CC_STAT_AREA])
    return np.where(labels == label, 255, 0).astype(np.uint8)


def grabcut_mask(rgb):
    """GrabCut initialised with a centred rectangle (for busy backgrounds)."""
    height, width = rgb.shape[:2]
    scale = min(1.0, 400 / max(height, width))
    small = (
        cv2.resize(rgb, None, fx=scale, fy=scale,
                   interpolation=cv2.INTER_AREA)
        if scale < 1 else rgb
    )
    bgr = cv2.cvtColor(small, cv2.COLOR_RGB2BGR)
    s_h, s_w = bgr.shape[:2]
    labels = np.zeros((s_h, s_w), np.uint8)
    rect = (int(0.04 * s_w), int(0.04 * s_h), int(0.92 * s_w),
            int(0.92 * s_h))
    cv2.grabCut(bgr, labels, rect, np.zeros((1, 65)), np.zeros((1, 65)),
                5, cv2.GC_INIT_WITH_RECT)
    foreground = np.where((labels == 1) | (labels == 3), 255, 0)
    foreground = cv2.resize(foreground.astype(np.uint8), (width, height),
                            interpolation=cv2.INTER_NEAREST)
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5, 5))
    foreground = cv2.morphologyEx(foreground, cv2.MORPH_OPEN, kernel)
    foreground = cv2.morphologyEx(foreground, cv2.MORPH_CLOSE, kernel)
    return fill_holes(largest_component(foreground))


def _segment_stages_uncached(rgb, kernel_size, method):
    """Otsu (saturation OR dark-gray) -> open -> close -> largest blob -> fill.

    Returns every intermediate image so the pipeline can be visualised.
    Otsu assumes a plain background; when its mask is implausible (or when
    requested) GrabCut is used instead.
    """
    bgr = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)
    gray = cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY)
    hsv = cv2.cvtColor(bgr, cv2.COLOR_BGR2HSV)
    saturation = hsv[:, :, 1]

    sat_threshold, sat_mask = cv2.threshold(
        saturation, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU
    )
    gray_threshold, dark_mask = cv2.threshold(
        gray, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU
    )
    combined = cv2.bitwise_or(sat_mask, dark_mask)

    kernel = cv2.getStructuringElement(
        cv2.MORPH_ELLIPSE, (kernel_size, kernel_size)
    )
    opened = cv2.morphologyEx(combined, cv2.MORPH_OPEN, kernel)
    closed = cv2.morphologyEx(opened, cv2.MORPH_CLOSE, kernel)
    component = largest_component(closed)
    otsu_mask = fill_holes(component)

    otsu_coverage = float(np.count_nonzero(otsu_mask) / otsu_mask.size)
    otsu_plausible = (
        MIN_PLAUSIBLE_COVERAGE <= otsu_coverage <= MAX_PLAUSIBLE_COVERAGE
    )
    use_grabcut = method == SEGMENTATION_METHODS[2] or (
        method == SEGMENTATION_METHODS[0] and not otsu_plausible
    )
    mask = grabcut_mask(rgb) if use_grabcut else otsu_mask

    return {
        "grabcut_used": use_grabcut,
        "otsu_mask": otsu_mask,
        "otsu_coverage": otsu_coverage,
        "gray": gray,
        "hsv": hsv,
        "saturation": saturation,
        "sat_threshold": float(sat_threshold),
        "gray_threshold": float(gray_threshold),
        "sat_mask": sat_mask,
        "dark_mask": dark_mask,
        "combined": combined,
        "opened": opened,
        "closed": closed,
        "component": component,
        "mask": mask,
    }


_segmentation_cache = {}


def segment_stages(rgb, kernel_size=5, method=DEFAULT_SEGMENTATION):
    """Cached wrapper: every tab segments the same image, so do it once."""
    key = (hashlib.md5(rgb.tobytes()).hexdigest(), rgb.shape, kernel_size,
           method)
    if key not in _segmentation_cache:
        if len(_segmentation_cache) >= 12:
            _segmentation_cache.pop(next(iter(_segmentation_cache)))
        _segmentation_cache[key] = _segment_stages_uncached(
            rgb, kernel_size, method
        )
    return _segmentation_cache[key]


def leaf_cutout(rgb, mask, background=235):
    out = np.full_like(rgb, background)
    out[mask > 0] = rgb[mask > 0]
    return out


def red_overlay(rgb, mask, strength=0.40):
    overlay = rgb.copy()
    fg = mask > 0
    overlay[fg] = (
        (1 - strength) * overlay[fg] + strength * np.array([230, 40, 40])
    ).astype(np.uint8)
    return overlay


def shape_analysis(rgb, mask):
    """Contour, convex hull, min-area rectangle + shape descriptors."""
    contours, _ = cv2.findContours(
        mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE
    )
    annotated = rgb.copy()
    if not contours:
        return annotated, None

    contour = max(contours, key=cv2.contourArea)
    area = float(cv2.contourArea(contour))
    perimeter = float(cv2.arcLength(contour, True))
    hull = cv2.convexHull(contour)
    hull_area = float(cv2.contourArea(hull))
    rect = cv2.minAreaRect(contour)
    (_cx, _cy), (rw, rh), _angle = rect
    long_side, short_side = max(rw, rh), max(min(rw, rh), 1e-6)
    x, y, w, h = cv2.boundingRect(contour)

    thickness = max(2, rgb.shape[1] // 300)
    cv2.drawContours(annotated, [hull], -1, (255, 200, 0), thickness)
    cv2.drawContours(annotated, [contour], -1, (0, 230, 90), thickness)
    box = cv2.boxPoints(rect).astype(np.int32)
    cv2.drawContours(annotated, [box], -1, (0, 190, 255), thickness)

    moments = cv2.moments(contour)
    if moments["m00"] > 0:
        mx = int(moments["m10"] / moments["m00"])
        my = int(moments["m01"] / moments["m00"])
        cv2.circle(annotated, (mx, my), thickness * 3, (255, 40, 40), -1)

    measures = {
        "area": area,
        "perimeter": perimeter,
        "aspect_ratio": long_side / short_side,
        "solidity": area / hull_area if hull_area > 0 else 0.0,
        "circularity": (4 * np.pi * area / perimeter ** 2)
        if perimeter > 0 else 0.0,
        "extent": area / (w * h) if w * h > 0 else 0.0,
    }
    return annotated, measures


def edge_density_in_leaf(gray, mask):
    edges = cv2.Canny(cv2.GaussianBlur(gray, (5, 5), 0), 60, 140)
    inside = mask > 0
    if not inside.any():
        return 0.0
    return float(np.count_nonzero(edges[inside]) / inside.sum())



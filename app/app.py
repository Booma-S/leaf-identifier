def smooth_image(rgb, kind, k):
    k = odd(k)
    if kind == "Median":
        return cv2.medianBlur(rgb, k)
    if kind == "Bilateral":
        return cv2.bilateralFilter(rgb, d=min(k, 15), sigmaColor=60,
                                   sigmaSpace=60)
    return cv2.GaussianBlur(rgb, (k, k), 0)


def morph_on_mask(mask, op, k):
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (odd(k), odd(k)))
    ops = {
        "Erosion": cv2.MORPH_ERODE,
        "Dilation": cv2.MORPH_DILATE,
        "Opening": cv2.MORPH_OPEN,
        "Closing": cv2.MORPH_CLOSE,
        "Gradient (outline)": cv2.MORPH_GRADIENT,
    }
    return cv2.morphologyEx(mask, ops[op], kernel)


def dip_lab(image, smooth_kind, smooth_k, clahe_clip, clahe_tile,
            canny_low, canny_high, morph_op, morph_k, lowpass_radius,
            sharpen_amount, seg_method=DEFAULT_SEGMENTATION):
    if image is None:
        return [], None
    try:
        rgb = to_rgb_array(image, LAB_MAX_SIDE)
        gray = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY)
        stages = segment_stages(rgb, method=seg_method)
        mask = stages["mask"]

        smoothed = smooth_image(rgb, smooth_kind, smooth_k)

        lab = cv2.cvtColor(rgb, cv2.COLOR_RGB2LAB)
        lab_he = lab.copy()
        lab_he[:, :, 0] = cv2.equalizeHist(lab[:, :, 0])
        he_rgb = cv2.cvtColor(lab_he, cv2.COLOR_LAB2RGB)

        clahe = cv2.createCLAHE(
            clipLimit=float(clahe_clip),
            tileGridSize=(int(clahe_tile), int(clahe_tile)),
        )
        lab_clahe = lab.copy()
        lab_clahe[:, :, 0] = clahe.apply(lab[:, :, 0])
        clahe_rgb = cv2.cvtColor(lab_clahe, cv2.COLOR_LAB2RGB)

        blurred = cv2.GaussianBlur(rgb, (0, 0), 2.0)
        sharpened = cv2.addWeighted(
            rgb, 1 + sharpen_amount, blurred, -sharpen_amount, 0
        )

        gray_blur = cv2.GaussianBlur(gray, (5, 5), 0)
        sobel_x = cv2.Sobel(gray_blur, cv2.CV_32F, 1, 0, ksize=3)
        sobel_y = cv2.Sobel(gray_blur, cv2.CV_32F, 0, 1, ksize=3)
        sobel_mag = normalise_u8(np.hypot(sobel_x, sobel_y))

        laplacian = normalise_u8(
            np.abs(cv2.Laplacian(gray_blur, cv2.CV_32F, ksize=3))
        )

        low, high = int(canny_low), int(max(canny_high, canny_low + 1))
        canny = cv2.Canny(gray_blur, low, high)

        green = rgb[:, :, 1]
        green_eq = cv2.createCLAHE(2.0, (8, 8)).apply(green)
        ksize = odd(max(9, rgb.shape[1] // 60))
        se = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (ksize, ksize))
        top_hat = cv2.morphologyEx(green_eq, cv2.MORPH_TOPHAT, se)
        black_hat = cv2.morphologyEx(green_eq, cv2.MORPH_BLACKHAT, se)
        veins = cv2.add(top_hat, black_hat)
        veins = normalise_u8(np.minimum(veins, np.percentile(veins, 99.5)))
        veins[mask == 0] = 0

        morphed = morph_on_mask(mask, morph_op, morph_k)

        # Frequency domain
        spectrum = np.fft.fftshift(np.fft.fft2(gray.astype(np.float32)))
        log_spectrum = normalise_u8(np.log1p(np.abs(spectrum)))
        rows, cols = gray.shape
        yy, xx = np.ogrid[:rows, :cols]
        dist2 = (yy - rows / 2) ** 2 + (xx - cols / 2) ** 2
        lowpass = np.exp(-dist2 / (2 * float(lowpass_radius) ** 2))
        filtered = np.fft.ifft2(np.fft.ifftshift(spectrum * lowpass)).real
        filtered = np.clip(filtered, 0, 255).astype(np.uint8)

        k_text = f"{odd(smooth_k)}x{odd(smooth_k)}"
        tile = int(clahe_tile)
        items = [
            (rgb, "Original"),
            (smoothed, f"{smooth_kind} filter ({k_text})"),
            (he_rgb, "Histogram equalisation"),
            (clahe_rgb, f"CLAHE {clahe_clip} / {tile}x{tile}"),
            (sharpened, f"Unsharp x{sharpen_amount:.2f}"),
            (gray3(sobel_mag), "Sobel magnitude"),
            (gray3(laplacian), "Laplacian"),
            (gray3(canny), f"Canny {low}/{high}"),
            (gray3(veins), "Vein map (top/black-hat)"),
            (gray3(morphed), f"Mask {morph_op.split()[0].lower()} "
                             f"{odd(morph_k)}x{odd(morph_k)}"),
            (gray3(log_spectrum), "FFT spectrum (log)"),
            (gray3(filtered),
             f"Low-pass D0={int(lowpass_radius)}"),
        ]

        # Intensity histograms: original vs HE vs CLAHE
        fig, ax = plt.subplots(1, 2, figsize=(12, 3.4))
        for img, name, colour in (
            (gray, "Original", "#64748b"),
            (cv2.cvtColor(he_rgb, cv2.COLOR_RGB2GRAY), "Global HE", "#dc2626"),
            (cv2.cvtColor(clahe_rgb, cv2.COLOR_RGB2GRAY), "CLAHE", "#16a34a"),
        ):
            hist = cv2.calcHist([img], [0], None, [256], [0, 256]).flatten()
            hist /= max(hist.sum(), 1)
            ax[0].plot(hist, color=colour, lw=1.6, label=name)
            ax[1].plot(np.cumsum(hist), color=colour, lw=1.8, label=name)
        ax[0].set_title("Grayscale histogram")
        ax[1].set_title("Cumulative distribution (CDF)")
        for a in ax:
            a.set_xlabel("Intensity")
            a.legend(frameon=False)
            a.grid(alpha=0.2)
            a.spines[["top", "right"]].set_visible(False)
        fig.tight_layout()

        return items, fig_to_array(fig)

    except Exception as error:
        print(f"DIP lab error: {error}")
        return [], None



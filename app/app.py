def compute_gradcam(batch, layer_name, class_index):
    feature_model = _gradcam_feature_models[layer_name]
    pooling, dropout, classifier = _gradcam_head
    tensor = tf.convert_to_tensor(batch)

    with tf.GradientTape() as tape:
        feature_maps, backbone_output = feature_model(tensor, training=False)
        pooled = pooling(backbone_output)
        pooled = dropout(pooled, training=False)
        predictions = classifier(pooled)
        score = predictions[:, class_index]

    gradients = tape.gradient(score, feature_maps)
    weights = tf.reduce_mean(gradients, axis=(1, 2))[0]
    heatmap = tf.reduce_sum(
        feature_maps[0] * weights[tf.newaxis, tf.newaxis, :], axis=-1
    )
    heatmap = tf.maximum(heatmap, 0).numpy()
    peak = heatmap.max()
    return heatmap / peak if peak > 0 else heatmap


def explain(image, layer_label, rank, alpha,
            seg_method=DEFAULT_SEGMENTATION):
    if image is None:
        return [], empty_state(
            "Grad-CAM appears here once an image is loaded.", "🧠"
        )
    if not _gradcam_feature_models:
        return [], empty_state(
            "Grad-CAM is unavailable for this model (layer names not "
            "found).", "⚠️"
        )
    try:
        batch = preprocess_image(image)
        probabilities = model(batch, training=False).numpy()[0]
        order = np.argsort(probabilities)[::-1]
        class_index = int(order[int(rank) - 1])
        class_label = class_names[class_index]
        class_conf = float(probabilities[class_index])

        layer_name = GRADCAM_LAYERS[layer_label]
        heat_small = compute_gradcam(batch, layer_name, class_index)

        rgb = to_rgb_array(image, DIP_MAX_SIDE)
        height, width = rgb.shape[:2]
        heat = cv2.resize(heat_small, (width, height),
                          interpolation=cv2.INTER_CUBIC)
        heat = np.clip(heat, 0, 1)

        coloured = cv2.applyColorMap(
            (heat * 255).astype(np.uint8), cv2.COLORMAP_JET
        )
        coloured = cv2.cvtColor(coloured, cv2.COLOR_BGR2RGB)
        # Blend proportionally to the heat so cold regions stay untouched.
        weight = (alpha * np.clip(heat * 1.4, 0, 1))[..., np.newaxis]
        overlay = (
            rgb.astype(np.float32) * (1 - weight)
            + coloured.astype(np.float32) * weight
        ).astype(np.uint8)

        peak_mask = (heat >= 0.6).astype(np.uint8) * 255
        peaks = rgb.copy()
        contours, _ = cv2.findContours(
            peak_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE
        )
        cv2.drawContours(peaks, contours, -1, (255, 40, 40),
                         max(2, width // 250))

        mask = segment_stages(rgb, method=seg_method)["mask"] > 0
        coverage = float(mask.mean())
        inside = float((heat * mask).sum() / max(heat.sum(), 1e-8))

        if (coverage < MIN_PLAUSIBLE_COVERAGE
                or coverage > MAX_PLAUSIBLE_COVERAGE):
            verdict = ("The segmentation mask is not plausible for this "
                       "image, so the leaf-versus-background comparison "
                       "cannot be trusted. Try another segmentation method.")
        elif inside >= 0.80:
            verdict = ("The attention is concentrated on the leaf region - "
                       "a healthy sign.")
        elif inside >= 0.60:
            verdict = ("Most attention falls on the leaf, but some spills "
                       "onto the background.")
        else:
            verdict = ("A large share of attention falls outside the "
                       "segmented leaf - the model may be using background "
                       "cues. Treat the prediction with care.")

        items = [
            (rgb, "Original"),
            (coloured, "Heatmap"),
            (overlay, "Overlay"),
            (peaks, "Peaks >= 60%"),
        ]
        summary = (
            '<div class="sec-title">Attention analysis</div>'
            + metric_cards([
                ("Explained class", class_label,
                 f"rank #{int(rank)} - {class_conf:.1%}"),
                ("Attention inside leaf", f"{inside:.0%}",
                 "heatmap mass within the segmented mask"),
                ("Leaf area", f"{coverage:.0%}",
                 "share of image covered by the leaf"),
                ("Feature map", f"{heat_small.shape[0]}x{heat_small.shape[1]}",
                 layer_name),
            ])
            + f'<div class="note-box">{esc(verdict)} <span class="muted">'
              "(Uses the DIP segmentation mask, so it is only as reliable as "
              "the mask.)</span></div>"
        )
        return items, summary

    except Exception as error:
        print(f"Grad-CAM error: {error}")
        return [], empty_state(f"Grad-CAM failed: {error}", "⚠️")


